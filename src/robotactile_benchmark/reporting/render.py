"""Deterministic dependency-light paper-table and curve rendering."""

from __future__ import annotations

import csv
import html
import io
from collections import defaultdict
from typing import Optional

from robotactile_benchmark.contracts import canonical_json
from robotactile_benchmark.reporting.summary_contracts import BenchmarkSummary


def _number(value: object) -> str:
    if value is None:
        return "N/A"
    if isinstance(value, float):
        return f"{value:.6f}"
    return str(value)


def render_summary_json(summary: BenchmarkSummary) -> bytes:
    return (canonical_json(summary.to_dict()) + "\n").encode("utf-8")


def render_per_task_csv(summary: BenchmarkSummary) -> bytes:
    stream = io.StringIO(newline="")
    writer = csv.writer(stream, lineterminator="\n")
    writer.writerow(
        (
            "task",
            "pair_count",
            "clean_sr",
            "no_touch_sr",
            "clean_gain",
            "fault_sr",
            "paired_delta_sr",
            "no_touch_relative_fault_delta",
            "tgr",
            "tgr_ineligibility_reason",
        )
    )
    for item in summary.tasks:
        writer.writerow(
            (
                item.task,
                item.pair_count,
                _number(item.clean_sr),
                _number(item.no_touch_sr),
                _number(item.clean_gain),
                _number(item.fault_sr),
                _number(item.paired_delta_sr),
                _number(item.no_touch_relative_fault_delta),
                _number(item.tgr),
                item.tgr_ineligibility_reason or "",
            )
        )
    return stream.getvalue().encode("utf-8")


def _cell_rows(summary: BenchmarkSummary) -> list[tuple[object, ...]]:
    return [
        (
            item.operator_id,
            item.axis,
            item.severity_level,
            _number(item.native_dose),
            item.native_unit,
            item.requested_count,
            item.eligible_count,
            _number(item.success_rate),
            _number(item.paired_delta_sr),
            _number(item.no_touch_relative_delta),
            _number(item.paired_delta_lower),
            _number(item.paired_delta_upper),
            _number(item.mcnemar_p_value),
            _number(item.holm_adjusted_p_value),
        )
        for item in summary.operator_cells
    ]


def render_operator_cells_csv(summary: BenchmarkSummary) -> bytes:
    stream = io.StringIO(newline="")
    writer = csv.writer(stream, lineterminator="\n")
    writer.writerow(
        (
            "operator_id",
            "axis",
            "severity_level",
            "native_dose",
            "native_unit",
            "requested_count",
            "eligible_count",
            "success_rate",
            "paired_delta_sr",
            "no_touch_relative_delta",
            "paired_delta_lower",
            "paired_delta_upper",
            "mcnemar_p_value",
            "holm_adjusted_p_value",
        )
    )
    writer.writerows(_cell_rows(summary))
    return stream.getvalue().encode("utf-8")


def render_native_dose_csv(summary: BenchmarkSummary) -> bytes:
    stream = io.StringIO(newline="")
    writer = csv.writer(stream, lineterminator="\n")
    writer.writerow(
        (
            "operator_id",
            "severity_level",
            "native_dose",
            "native_unit",
            "success_rate",
        )
    )
    for item in summary.native_dose_curves:
        writer.writerow(
            (
                item.operator_id,
                item.severity_level,
                _number(item.native_dose),
                item.native_unit,
                _number(item.success_rate),
            )
        )
    return stream.getvalue().encode("utf-8")


def _latex_escape(value: str) -> str:
    replacements = {
        "\\": r"\textbackslash{}",
        "_": r"\_",
        "&": r"\&",
        "%": r"\%",
        "#": r"\#",
    }
    return "".join(replacements.get(character, character) for character in value)


def _latex_metric(value: Optional[float]) -> str:
    return "N/A" if value is None else f"{value:.3f}"


def render_summary_table_tex(summary: BenchmarkSummary) -> bytes:
    tgr = _latex_metric(summary.macro_tgr)
    lines = [
        "% Generated by robotactile-benchmark; do not edit by hand.",
        r"\begin{tabular}{lrrrrr}",
        r"\toprule",
        "Task & Clean SR & No-touch SR & Fault SR & $\\Delta$SR & TGR \\\\",
        r"\midrule",
    ]
    for item in summary.tasks:
        task_tgr = _latex_metric(item.tgr)
        lines.append(
            f"{_latex_escape(item.task)} & {item.clean_sr:.3f} & "
            f"{_latex_metric(item.no_touch_sr)} & {item.fault_sr:.3f} & "
            f"{item.paired_delta_sr:.3f} & {task_tgr} \\\\"
        )
    lines.extend(
        [
            r"\midrule",
            f"Macro & {summary.macro_clean_sr:.3f} & "
            f"{_latex_metric(summary.macro_no_touch_sr)} & "
            f"{summary.macro_fault_sr:.3f} & "
            f"{summary.macro_paired_delta_sr:.3f} & {tgr} \\\\ ",
            r"\bottomrule",
            r"\end{tabular}",
            "",
        ]
    )
    return "\n".join(lines).encode("utf-8")


def render_native_dose_svg(summary: BenchmarkSummary) -> bytes:
    by_operator = defaultdict(list)
    for item in summary.operator_cells:
        by_operator[item.operator_id].append(item)
    width = 900
    row_height = 82
    height = 42 + row_height * len(by_operator)
    parts = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">',
        '<rect width="100%" height="100%" fill="white"/>',
        '<text x="18" y="24" font-family="sans-serif" font-size="15" font-weight="600">Within-operator native-dose curves (severity is not cross-operator dose)</text>',
    ]
    colors = {
        "availability": "#E69F00",
        "fidelity": "#0072B2",
        "temporal": "#009E73",
        "context": "#CC79A7",
    }
    for row, (operator, cells) in enumerate(sorted(by_operator.items())):
        y_top = 42 + row * row_height
        y_axis = y_top + 52
        parts.append(
            f'<text x="18" y="{y_top + 16}" font-family="sans-serif" font-size="11">{html.escape(operator)}</text>'
        )
        parts.append(
            f'<line x1="330" y1="{y_axis}" x2="870" y2="{y_axis}" stroke="#777" stroke-width="1"/>'
        )
        points = []
        for index, cell in enumerate(cells):
            x = 350 + index * (500 / max(1, len(cells) - 1))
            score = 0.0 if cell.success_rate is None else cell.success_rate
            y = y_axis - 42 * score
            points.append(f"{x:.1f},{y:.1f}")
            parts.append(
                f'<circle cx="{x:.1f}" cy="{y:.1f}" r="3.5" fill="{colors[cell.axis]}"/>'
            )
            parts.append(
                f'<text x="{x:.1f}" y="{y_axis + 15}" text-anchor="middle" font-family="sans-serif" font-size="9">{html.escape(_number(cell.native_dose))}</text>'
            )
        joined_points = " ".join(points)
        parts.append(
            f'<polyline points="{joined_points}" fill="none" stroke="{colors[cells[0].axis]}" stroke-width="2"/>'
        )
        parts.append(
            f'<text x="875" y="{y_axis + 15}" text-anchor="end" font-family="sans-serif" font-size="9">{html.escape(cells[0].native_unit)}</text>'
        )
    parts.append("</svg>")
    return ("\n".join(parts) + "\n").encode("utf-8")


def rendered_members(summary: BenchmarkSummary) -> dict[str, bytes]:
    """Return the exact non-receipt report inventory."""

    return {
        "native_dose_curves.csv": render_native_dose_csv(summary),
        "native_dose_curves.svg": render_native_dose_svg(summary),
        "operator_cells.csv": render_operator_cells_csv(summary),
        "per_task.csv": render_per_task_csv(summary),
        "summary.json": render_summary_json(summary),
        "summary_table.tex": render_summary_table_tex(summary),
    }
